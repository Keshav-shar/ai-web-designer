"""build_shell.py - an engine demo: a theme and About page composed by our engine on a dreamy ethereal query.

Note: the Cosmogon Labs app is hand-designed now (web/app/theme/cosmogon.css) and no longer imports these outputs;
they remain an example of an engine-composed shell.

    D:\\caches\\venvs\\uifp\\Scripts\\python.exe tools\\build_shell.py [--family dreamy-ethereal] [--theme light]

One engine run (lab -> brief -> compose, no model; the pi cursor is not advanced) writes:
    web/app/theme/tokens.css, tokens.json, web/app/fonts.ts   the header / footer / app theme (that run's tokens)
    web/content/about.generated.ts                              the composed About sections (validated HTML)
    web/public/about/assets/*.webp                              the folder-section images those sections use
Copy for the About page comes from contracts/about_copy.json; design and imagery come from the engine.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "worker"))
sys.path.insert(0, str(ROOT / "tools"))
import worker as W  # noqa: E402
from theme import report, theme_from_brief, write_theme  # noqa: E402

WEB = ROOT / "web"
SECTIONS = ["hero", "how_it_works", "showcase", "faq", "cta_band"]
SPLIT = {"full_query": "serpman studio, a taste engine that turns one sentence into a designed website",
         "vibe_query": "dreamy ethereal", "category_hint": "devsaas", "brand_name": "serpman studio",
         "audience": "designers and founders", "must_sections": [], "source": "fallback"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--family", default="dreamy-ethereal")
    ap.add_argument("--theme", default="light", choices=["auto", "light", "dark"])
    a = ap.parse_args(argv)

    copy = json.loads((ROOT / "contracts" / "about_copy.json").read_text(encoding="utf-8"))
    eng = W.Engine()
    out = W.run_job(eng, None, SPLIT["full_query"], SPLIT, None, a.theme,
                    lambda st, msg, data=None: print(f"[{st}] {msg}", flush=True),
                    copy=copy, serve=False, force_fam=a.family, sections_override=SECTIONS)
    brief = out["brief"]

    theme = theme_from_brief(brief)
    write_theme(theme)
    report(theme)

    html = "\n".join(s["html"] for s in out["sections"])
    used = sorted(set(re.findall(r'assets/[a-z0-9]{12}\.webp', html)))
    html = html.replace('href="#studio"', 'href="/"')
    html = re.sub(r'(src|href)="assets/', r'\1="/about/assets/', html)
    dest = WEB / "public" / "about" / "assets"
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for rel in used:
        (dest / rel.split("/", 1)[1]).write_bytes(out["files"][rel])
    meta = {"family": brief["meta"]["routed_family"], "sections": [s["id"] for s in out["sections"]],
            "images": len(used), "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "fonts": [brief["fonts"]["heading"]["family"], brief["fonts"]["body"]["family"]]}
    (WEB / "content").mkdir(exist_ok=True)
    (WEB / "content" / "about.generated.ts").write_text(
        "// generated by tools/build_shell.py from one serpman engine run - do not edit by hand\n"
        f"export const ABOUT_META = {json.dumps(meta)} as const;\n"
        f"export const ABOUT_HTML = {json.dumps(html)};\n", encoding="utf-8")
    (ROOT / "fixtures").mkdir(exist_ok=True)
    (ROOT / "fixtures" / "brief_shell.json").write_text(json.dumps(brief, indent=1), encoding="utf-8")
    print(f"about: {len(out['sections'])} sections, {len(used)} images -> web/content/about.generated.ts, web/public/about/assets/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
