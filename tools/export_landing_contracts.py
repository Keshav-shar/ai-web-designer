"""export_landing_contracts.py - write the landing-page agents' contracts to contracts/agents/ for review.

    D:\\caches\\venvs\\uifp\\Scripts\\python.exe tools\\export_landing_contracts.py [fixture-name]

The schemas are built per run by worker/landing/schemas.py, because their enums are that run's section ids, element
ids and palette names. This writes them bound to one recorded fixture, plus the merged design document A5
receives and the fallback page spec (deterministic defaults), so the contracts can be read and diffed like files.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "worker"))
import brief as B  # noqa: E402
import split as SP  # noqa: E402
from landing import flow, handoff, schemas as sc, state as S  # noqa: E402

OUT = ROOT / "contracts" / "agents"


def main(name: str) -> None:
    d = json.loads((ROOT / "fixtures" / "landing" / f"{name}.json").read_text(encoding="utf-8"))
    res = {k: Path(v) for k, v in d["resolve"].items()}
    sp = SP.fallback(d["q"])
    sp["vibe_query"] = d["q"]
    resolve = lambda f, i: res.get(f"{f}/{i}")  # noqa: E731
    text_lines = lambda f, i: {"clip": d["text"][f"{f}/{i}"]} if f"{f}/{i}" in d["text"] else None  # noqa: E731
    # fixtures carry no CLIP encoder: the recorded lab sections stand in for brief.prompt_context
    brief, files = B.build_brief(d["o"], query=sp["full_query"], split=sp, sections_src=d["o"]["sections"],
                                 resolve=resolve, text_lines=text_lines)
    h = handoff.build(d["o"], sp, brief, files, resolve=resolve, text_lines=text_lines)
    st, spec, _ = flow.deterministic(h)
    OUT.mkdir(parents=True, exist_ok=True)
    files = {
        "a1.schema.json": sc.a1(),
        "a2.schema.json": sc.a2(*flow.a2_enums(st)),
        "a3.schema.json": sc.a3(flow.a2_enums(st)[0], flow.a2_enums(st)[2]),
        "a4.schema.json": sc.a4(flow.a2_enums(st)[1]),
        "landing_spec.example.json": spec,
        "fallback_spec.example.json": flow.fallback(st, h)[0],
        "slices.example.json": {"digest": S.digest(st), **{a: S.slice_for(st, a) for a in ("a1", "a2", "a3", "a4")}},
    }
    for fn, obj in files.items():
        (OUT / fn).write_text(json.dumps({"$comment": f"generated by tools/export_landing_contracts.py from fixture "
                                          f"'{name}'; enums are per run", **obj} if fn.endswith("schema.json") else obj,
                                         indent=1, ensure_ascii=False), encoding="utf-8")
        print(f"wrote {OUT / fn}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "neon-synthwave-music-festival")
