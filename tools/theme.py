"""theme.py - write the web app's theme files from one theme dict (shared by export_tokens.py and build_shell.py).

    web/app/theme/tokens.css   :root custom properties (colour roles, derived, --visual-N, type scale, heading style)
    web/app/theme/tokens.json  the same plus provenance (family, vibe, overrides, contrast)
    web/app/fonts.ts           next/font/google loaders, exposed as --nf-heading / --nf-body
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "web"
sys.path.insert(0, str(ROOT / "worker"))
import guardrails as g  # noqa: E402


def ident(family: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", family).strip("_")


def theme_from_brief(brief: dict) -> dict:
    f = brief["fonts"]
    italic = bool(f.get("pairing", {}).get("heading_italic"))
    return {
        "source": {"query": brief["meta"]["query"], "family": brief["meta"]["routed_family"],
                   "vibe_query": brief["meta"]["vibe_query"], "pi_log": brief["meta"].get("pi_log", [])},
        "vibe": brief["vibe"], "color": brief["tokens"]["color"], "derived": brief["tokens"]["derived"],
        "visuals": brief["typography"].get("visuals", []), "type": brief["tokens"]["type"],
        "fonts": {"heading": f["heading"]["family"], "heading_italic": italic, "body": f["body"]["family"],
                  "heading_css": f["heading"].get("google_css") or g.google_css(f["heading"]["family"], italic),
                  "body_css": f["body"].get("google_css") or g.google_css(f["body"]["family"], False)},
        "contrast": brief["tokens"]["contrast"], "overrides": brief["typography"].get("overrides", []),
        "sections": [s["id"] for s in brief["sections"]],
    }


def write_theme(theme: dict, web: Path = WEB) -> None:
    failing = [c for c in theme["contrast"] if not c["pass"]]
    if failing:
        raise SystemExit(f"contrast still failing, not writing a theme: {failing}")
    (web / "app" / "theme").mkdir(parents=True, exist_ok=True)
    (web / "app" / "theme" / "tokens.json").write_text(json.dumps(theme, indent=2), encoding="utf-8")
    lines = ["/* generated by tools/theme.py from a serpman engine run - do not edit by hand */", ":root {"]
    for k, val in {**theme["color"], **theme["derived"]}.items():
        lines.append(f"  {k}: {val};")
    for i, val in enumerate(theme["visuals"]):
        lines.append(f"  --visual-{i + 1}: {val};")
    for k, val in theme["type"].items():
        lines.append(f"  {k}: {val};")
    lines.append(f"  --heading-style: {'italic' if theme['fonts']['heading_italic'] else 'normal'};")
    lines.append("}")
    (web / "app" / "theme" / "tokens.css").write_text("\n".join(lines) + "\n", encoding="utf-8")

    heading, body, italic = theme["fonts"]["heading"], theme["fonts"]["body"], theme["fonts"]["heading_italic"]
    hi, bi = ident(heading), ident(body)
    styles = g.font_catalog().get(heading, {}).get("styles", set())
    weights = [w for w in ("400", "500", "600") if w in styles] or ["400"]
    imports = hi if hi == bi else f"{hi}, {bi}"
    style = '["normal", "italic"]' if italic else '["normal"]'
    ts = ("// generated by tools/theme.py - do not edit by hand\n"
          f'import {{ {imports} }} from "next/font/google";\n\n'
          f'export const headingFont = {hi}({{ subsets: ["latin"], weight: {json.dumps(weights)}, style: {style}, '
          f'variable: "--nf-heading", display: "swap" }});\n')
    ts += (f'export const bodyFont = {bi}({{ subsets: ["latin"], variable: "--nf-body", display: "swap" }});\n'
           if bi != hi else "export const bodyFont = headingFont;\n")
    (web / "app" / "fonts.ts").write_text(ts, encoding="utf-8")


def report(theme: dict) -> None:
    print(f"theme: family {theme['source']['family']}  heading {theme['fonts']['heading']}"
          f"{' (italic)' if theme['fonts']['heading_italic'] else ''}  body {theme['fonts']['body']}")
    for r in theme["contrast"]:
        print(f"  {r['pair']:<22} {r['ratio']:>5}  {'ok' if r['pass'] else 'FAIL'}")
    print(f"  {len(theme['overrides'])} override(s)")
